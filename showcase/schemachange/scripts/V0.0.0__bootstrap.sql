USE ROLE SECURITYADMIN;
-- create bootstrap network policy
CREATE NETWORK POLICY IF NOT EXISTS ENABLED_GIT_IPV4_NETWORK;
ALTER NETWORK POLICY ENABLED_GIT_IPV4_NETWORK
    SET ALLOWED_IP_LIST = (
          '13.54.198.44'
        , '52.63.120.234'
        , '52.64.12.252'
        , '52.64.92.223'
        , '52.65.28.184'
        , '52.65.220.188'
    );

-- create bootstrap roles
CREATE ROLE IS NOT EXISTS GITHUB_INTEGRATION_ROLE_S;
ALTER ROLE GITHUB_INTEGRATION_ROLE_S
    SET COMMENT = $$Overarching GitHUB role for managing account wide changes$$;
CREATE ROLE IS NOT EXISTS DEV_GITHUB_INTEGRATION_ROLE_S;
ALTER ROLE DEV_GITHUB_INTEGRATION_ROLE_S
    SET COMMENT = $$GitHUB role for managing DEV changes$$;
CREATE ROLE IS NOT EXISTS TST_GITHUB_INTEGRATION_ROLE_S;
ALTER ROLE TST_GITHUB_INTEGRATION_ROLE_S
    SET COMMENT = $$GitHUB role for managing TST changes$$;
CREATE ROLE IS NOT EXISTS PST_GITHUB_INTEGRATION_ROLE_S;
ALTER ROLE PST_GITHUB_INTEGRATION_ROLE_S
    SET COMMENT = $$GitHUB role for managing PST changes$$;
CREATE ROLE IS NOT EXISTS PRD_GITHUB_INTEGRATION_ROLE_S;
ALTER ROLE PRD_GITHUB_INTEGRATION_ROLE_S
    SET COMMENT = $$GitHUB role for managing PRD changes$$;
GRANT ROLE GITHUB_INTEGRATION_ROLE_S TO ROLE SECURITYADMIN;
GRANT ROLE GITHUB_INTEGRATION_ROLE_S TO ROLE SYSADMIN;
GRANT ROLE DEV_GITHUB_INTEGRATION_ROLE_S TO ROLE GITHUB_INTEGRATION_ROLE_S;
GRANT ROLE TST_GITHUB_INTEGRATION_ROLE_S TO ROLE GITHUB_INTEGRATION_ROLE_S;
GRANT ROLE PST_GITHUB_INTEGRATION_ROLE_S TO ROLE GITHUB_INTEGRATION_ROLE_S;
GRANT ROLE PRD_GITHUB_INTEGRATION_ROLE_S TO ROLE GITHUB_INTEGRATION_ROLE_S;

USE ROLE SYSADMIN;
-- create bootstrap warehouse
CREATE WAREHOUSE IF NOT EXISTS ADMIN_XS_WH;
ALTER WAREHOUSE ADMIN_XS_WH
    SET WAREHOUSE_TYPE = STANDARD
        WAREHOUSE_SIZE = XSMALL
        MAX_CLUSTER_COUNT = 1
        MIN_CLUSTER_COUNT = 1
        SCALING_POLICY = STANDARD
        AUTO_SUSPEND = 600
        AUTO_RESUME = TRUE
        INITIALLY_SUSPENDED = TRUE
        COMMENT = $$Warehouse used for administrative tasks$$
        ENABLE_QUERY_ACCELERATION = FALSE
        QUERY_ACCELERATION_MAX_SCALE_FACTOR = 0;
USE ROLE SECURITYADMIN;
GRANT USAGE ON WAREHOUSE ADMIN_XS_WH TO ROLE GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON WAREHOUSE ADMIN_XS_WH TO ROLE DEV_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON WAREHOUSE ADMIN_XS_WH TO ROLE TST_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON WAREHOUSE ADMIN_XS_WH TO ROLE PST_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON WAREHOUSE ADMIN_XS_WH TO ROLE PRD_GITHUB_INTEGRATION_ROLE_S;

USE ROLE USERADMIN;
-- create bootstrap user
CREATE USER IF NOT EXISTS GITHUB_INTEGRATION_USER;
ALTER USER GITHUB_INTEGRATION_USER
    SET DISABLED = false
        DAYS_TO_EXPIRY = NULL
        DEFAULT_WAREHOUSE = 'ADMIN_XS_WH'
        DEFAULT_NAMESPACE = 'METADATA.SCHEMACHANGE'
        DEFAULT_ROLE = 'GITHUB_INTEGRATION_ROLE_S'
        RSA_PUBLIC_KEY = <replace with a string>
        RSA_PUBLIC_KEY_FP = <replace with a string>
        TYPE = SERVICE
        COMMENT = $$GitHUB user used to connect to Snowflake$$
        NETWORK_POLICY = 'ENABLED_GIT_IPV4_NETWORK'
;

USE ROLE SECURITYADMIN;
GRANT ROLE GITHUB_INTEGRATION_ROLE_S TO USER GITHUB_INTEGRATION_USER;
GRANT ROLE DEV_GITHUB_INTEGRATION_ROLE_S TO USER GITHUB_INTEGRATION_USER;
GRANT ROLE TST_GITHUB_INTEGRATION_ROLE_S TO USER GITHUB_INTEGRATION_USER;
GRANT ROLE PST_GITHUB_INTEGRATION_ROLE_S TO USER GITHUB_INTEGRATION_USER;
GRANT ROLE PRD_GITHUB_INTEGRATION_ROLE_S TO USER GITHUB_INTEGRATION_USER;

-- create initial database
USE ROLE GITHUB_INTEGRATION_ROLE_S;
CREATE DATABASE IF NOT EXISTS METADATA;
ALTER DATABASE METADATA
    SET COMMENT = $$This database holds schema management tables$$;
CREATE SCHEMA IF NOT EXISTS METADATA.SCHEMACHANGE;
ALTER SCHEMA METADATA.SCHEMACHANGE
    SET COMMENT = $$This schema is where the schema management tables live$$;
CREATE TABLE IF NOT EXISTS METADATA.SCHEMACHANGE.GLOBAL_HISTORY
    ( VERSION        VARCHAR
    , DESCRIPTION    VARCHAR
    , SCRIPT         VARCHAR
    , SCRIPT_TYPE    VARCHAR
    , CHECKSUM       VARCHAR
    , EXECUTION_TIME NUMBER
    , STATUS         VARCHAR
    , INSTALLED_BY   VARCHAR
    , INSTALLED_ON   TIMESTAMP_LTZ
    );
ALTER TABLE METADATA.SCHEMACHANGE.GLOBAL_HISTORY
    SET DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = $$Account wide changes from common are managed here$$;
USE ROLE SECURITYADMIN;
GRANT USAGE ON DATABASE METADATA TO ROLE DEV_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON DATABASE METADATA TO ROLE TST_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON DATABASE METADATA TO ROLE PST_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON DATABASE METADATA TO ROLE PRD_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON SCHEMA METADATA.SCHEMACHANGE TO ROLE DEV_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON SCHEMA METADATA.SCHEMACHANGE TO ROLE TST_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON SCHEMA METADATA.SCHEMACHANGE TO ROLE PST_GITHUB_INTEGRATION_ROLE_S;
GRANT USAGE ON SCHEMA METADATA.SCHEMACHANGE TO ROLE PRD_GITHUB_INTEGRATION_ROLE_S;

USE ROLE DEV_GITHUB_INTEGRATION_ROLE_S;
CREATE TABLE IF NOT EXISTS METADATA.SCHEMACHANGE.DEV_CHANGE_HISTORY
    LIKE METADATA.SCHEMACHANGE.CHANGE_HISTORY;
ALTER TABLE METADATA.SCHEMACHANGE.DEV_CHANGE_HISTORY
    SET DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = $$DEV environment repo specific changes are managed here$$;
USE ROLE TST_GITHUB_INTEGRATION_ROLE_S;
CREATE TABLE IF NOT EXISTS METADATA.SCHEMACHANGE.TST_CHANGE_HISTORY
    LIKE METADATA.SCHEMACHANGE.CHANGE_HISTORY;
ALTER TABLE METADATA.SCHEMACHANGE.TST_CHANGE_HISTORY
    SET DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = $$TST environment repo specific changes are managed here$$;
USE ROLE PST_GITHUB_INTEGRATION_ROLE_S;
CREATE TABLE IF NOT EXISTS METADATA.SCHEMACHANGE.PST_CHANGE_HISTORY
    LIKE METADATA.SCHEMACHANGE.CHANGE_HISTORY;
ALTER TABLE METADATA.SCHEMACHANGE.PST_CHANGE_HISTORY
    SET DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = $$PST environment repo specific changes are managed here$$;
USE ROLE PRD_GITHUB_INTEGRATION_ROLE_S;
CREATE TABLE IF NOT EXISTS METADATA.SCHEMACHANGE.PRD_CHANGE_HISTORY
    LIKE METADATA.SCHEMACHANGE.CHANGE_HISTORY;
ALTER TABLE METADATA.SCHEMACHANGE.PRD_CHANGE_HISTORY
    SET DATA_RETENTION_TIME_IN_DAYS = 1
        COMMENT = $$PRD environment repo specific changes are managed here$$;
